def sql_str(s):
    return "'" + s.replace("'", "''") + "'"

def nodes():
    """(key, expected name, parent key, icon, colour) depth-first."""
    for key, name, icon, colour, children in TREE:
        yield key, name, None, icon, colour
        for child in children:
            yield child[0], child[1], key, 0, 0

def main():
    out = ['-- Generated by prod-staging/catalogue-v31/tree.py', 'SET @base = (SELECT MAX(id) FROM catalogue_pages);']
    for n, (key, (name, icon, colour, fuse)) in enumerate(FOLDERS.items(), 1):
        out.append(f"INSERT INTO catalogue_pages (id, order_id, parent_id, icon, colour, index_visible, is_club_only, name_index, link_list, name, layout, fuse, body) "
                   f"VALUES (@base + {n}, 0, -1, {icon}, {colour}, 1, 0, {sql_str(name)}, '', {sql_str(name)}, '', {sql_str(fuse)}, '');")
        out.append(f"SET @{key} = @base + {n};")
    ref = lambda k: f"@{k}" if isinstance(k, str) else str(k)
    order = 0
    for key, name, parent, icon, colour in nodes():
        order += 1
        if isinstance(key, str):
            out.append(f"UPDATE catalogue_pages SET order_id = {order}, parent_id = -1 WHERE id = @{key};")
            continue
        out.append(f"UPDATE catalogue_pages SET order_id = {order}, parent_id = {ref(parent) if parent else -1}, icon = {icon}, colour = {colour} "
                   f"WHERE id = {key} AND name = {sql_str(name)};")
    out.append(f"-- Pages not in the tree keep their parent and go after it, in their old order.")
    listed = ', '.join(str(k) for k, *_ in nodes() if not isinstance(k, str))
    out.append(f"UPDATE catalogue_pages SET order_id = {order} + order_id WHERE id NOT IN ({listed}) AND id NOT IN (@MOEBLER, @STAFF);")
    print('\n'.join(out))

def check():
    """Lines of `id<TAB>name` on stdin (SELECT id, name FROM catalogue_pages): report mismatches."""
    have = dict(line.rstrip('\n').split('\t', 1) for line in sys.stdin if '\t' in line)
    bad = [(k, n, have.get(str(k))) for k, n, *_ in nodes() if not isinstance(k, str) and have.get(str(k)) != n]
    missing = [i for i in have if int(i) not in {k for k, *_ in nodes() if not isinstance(k, str)}]
    for k, n, h in bad: print(f'mismatch: {k} expected {n!r}, database has {h!r}')
    print(f'{len(bad)} mismatches; pages not in the tree: {", ".join(have[i] + " (" + i + ")" for i in missing) or "none"}')

if __name__ == '__main__':
    check() if sys.argv[1:] == ['check'] else main()
